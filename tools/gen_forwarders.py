"""Writes src/common/fwd_<dll>.h: linker pragmas forwarding every export of a System32 DLL, so our
proxy DLL can stand in for it.   python gen_forwarders.py winmm"""
import os
import sys

import pefile

name = sys.argv[1]
src = os.path.join(os.environ["WINDIR"], "System32", name + ".dll")
pe = pefile.PE(src)
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "common", "fwd_%s.h" % name)
target = src[:-4].replace("\\", "\\\\")  # C:\\WINDOWS\\System32\\winmm inside the pragma string
with open(out, "w") as f:
    f.write("// Generated by tools/gen_forwarders.py from %s: forwards every export to the system DLL.\n" % src)
    f.write("#pragma once\n")
    for e in pe.DIRECTORY_ENTRY_EXPORT.symbols:
        if e.name:
            n = e.name.decode()
            # a DLL that implements an export itself defines BW2_OWN_<name> before including this
            f.write('#ifndef BW2_OWN_%s\n#pragma comment(linker, "/export:%s=%s.%s,@%d")\n#endif\n' % (n, n, target, n, e.ordinal))
        else:
            f.write('#pragma comment(linker, "/export:__ord%d=%s.#%d,@%d,NONAME")\n' % (e.ordinal, target, e.ordinal, e.ordinal))
print("wrote", os.path.normpath(out))
